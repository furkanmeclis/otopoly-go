#!/usr/bin/env node
// Claude Code hooks for this project. Usage: node guard.mjs <protect|lint|typecheck>
import { execFileSync } from 'node:child_process';
import path from 'node:path';

const mode = process.argv[2];
const root = process.env.CLAUDE_PROJECT_DIR || process.cwd();

let raw = '';
for await (const chunk of process.stdin) raw += chunk;
const input = raw ? JSON.parse(raw) : {};
const filePath = input.tool_input?.file_path ?? '';
const rel = filePath ? path.relative(root, path.resolve(root, filePath)) : '';

function run(cmd, args) {
  try {
    execFileSync(cmd, args, { cwd: root, stdio: 'pipe', encoding: 'utf8' });
    return null;
  } catch (e) {
    return `${e.stdout ?? ''}${e.stderr ?? ''}`.trim() || String(e);
  }
}

if (mode === 'protect') {
  // ios/ and android/ are generated by prebuild (CNG); lock files are owned by the package manager.
  const blocked =
    /^(ios|android)\//.test(rel) ||
    /^(package-lock\.json|bun\.lockb?|yarn\.lock|pnpm-lock\.yaml)$/.test(rel);
  if (blocked) {
    console.error(
      `Blocked edit to ${rel}: native folders are generated by prebuild (configure via app.json / config plugins), ` +
        'and lock files must only change through `npx expo install`.'
    );
    process.exit(2);
  }
}

if (mode === 'lint') {
  if (!/\.(ts|tsx|js|jsx)$/.test(rel) || rel.startsWith('..') || rel.startsWith('node_modules')) process.exit(0);
  const out = run('npx', ['eslint', '--fix', rel]);
  if (out) {
    console.error(`ESLint issues in ${rel} (auto-fixable ones were fixed):\n${out}`);
    process.exit(2);
  }
}

if (mode === 'typecheck') {
  if (input.stop_hook_active) process.exit(0); // avoid loops: only block the first stop
  const out = run('npx', ['tsc', '--noEmit']);
  if (out) {
    console.error(`TypeScript errors — fix before finishing:\n${out.slice(0, 4000)}`);
    process.exit(2);
  }
}
