#!/usr/bin/env node
// Copies the web frontend translation catalogs into src/locales and regenerates src/locales/index.ts.
// Usage: node scripts/sync-locales.mjs [path-to-web-locales]
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const source = path.resolve(process.argv[2] ?? path.join(root, '../../Projects/otopoly-go/frontend/src/locales'));
const target = path.join(root, 'src/locales');
const locales = ['tr', 'en'];

if (!fs.existsSync(source)) {
  console.error(`Web locales not found at ${source}`);
  process.exit(1);
}

for (const locale of locales) {
  fs.mkdirSync(path.join(target, locale), { recursive: true });
  for (const file of fs.readdirSync(path.join(source, locale))) {
    if (file.endsWith('.json')) fs.copyFileSync(path.join(source, locale, file), path.join(target, locale, file));
  }
}

// Mobile-only keys live in src/locales/mobile/{locale}.json and are merged as the `mobile` namespace.
const names = fs
  .readdirSync(path.join(target, 'tr'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -5))
  .sort();
const ident = (locale, name) => locale + name.split('_').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

const lines = [
  '// Generated by scripts/sync-locales.mjs — do not edit by hand.',
  '// Same catalogs as the web frontend (otopoly-go/frontend/src/locales).',
  '',
];
for (const locale of locales) {
  for (const name of names) lines.push(`import ${ident(locale, name)} from './${locale}/${name}.json';`);
  lines.push(`import ${locale}Mobile from './mobile/${locale}.json';`);
}
lines.push('', 'export const catalogs = {');
for (const locale of locales) {
  lines.push(`  ${locale}: {`);
  for (const name of names) lines.push(`    ${name}: ${ident(locale, name)},`);
  lines.push(`    mobile: ${locale}Mobile,`);
  lines.push('  },');
}
lines.push('} as const;', '', 'export type AppLocale = keyof typeof catalogs;', '');
fs.writeFileSync(path.join(target, 'index.ts'), lines.join('\n'));
console.log(`Synced ${names.length} namespaces × ${locales.length} locales from ${source}`);
