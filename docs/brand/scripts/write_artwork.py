"""Write frontend/src/components/brand/artwork.ts from geo.json (see normalize.py).

Usage: python3 -I write_artwork.py <geo.json> <artwork.ts>
Run prettier on the output afterwards.
"""
import json
import sys

g = json.load(open(sys.argv[1]))


def part(name, o):
    lines = [f"export const {name} = {{", f'  viewBox: "{o["viewBox"]}",',
             "  /** Outline width of the left tile in the dark variant. */", f'  stroke: {o["stroke"]},']
    for k in ("tile", "accent"):
        v = o[k]
        if isinstance(v, dict):
            lines.append(f"  {k}: {{ x: {v['x']}, y: {v['y']}, width: {v['width']}, height: {v['height']}, rx: {v['rx']} }},")
        else:
            lines.append(f'  {k}: "{v}",')
    for k in ("o", "p", "star", "text"):
        if k in o:
            lines.append(f'  {k}: "{o[k]}",')
    lines.append("} as const;")
    return "\n".join(lines)


HEADER = '''/**
 * Otopoly logo geometry, normalized from the logo pack in `docs/brand/logo-pack`.
 * Generated by docs/brand/scripts/write_artwork.py.
 *
 * Both lockups share the same parts:
 * - `tile`   left block behind the O (espresso fill in light, cream outline in dark)
 * - `accent` right terracotta block behind the P
 * - `o`, `p`, `star` glyphs (evenodd for `o` / `p`)
 * - `text`   OTOPOLY letters (horizontal lockup only)
 *
 * A part is either path data or a rounded rect.
 */

export type BrandRect = {
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
  readonly rx: number;
};

export type BrandShape = string | BrandRect;

/** Exact logo-pack colours. */
export const brandLogoColors = {
  espresso: "#2B201A",
  cream: "#FEF9F5",
  accent: "#E26B41",
  white: "#FFFFFF",
} as const;

/** OP mark (from "Icon"). */
'''

with open(sys.argv[2], "w") as f:
    f.write(HEADER + part("brandMark", g["mark"]) + '\n\n/** Horizontal OP + OTOPOLY lockup (from "Logo 2"). */\n' + part("brandWordmark", g["wordmark"]) + "\n")
